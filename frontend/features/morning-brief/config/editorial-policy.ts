import type { CategoryId } from './content-policy.ts';

export type EditorialItem = {
  category: CategoryId;
  eventKey: string;
  headline: string;
  summary: string;
  updateType: 'new' | 'material_update';
  materialUpdateReason?: string;
  sourceUrls: string[];
};

